export const queryIntelligence = async (
  userPrompt: string,
): Promise<string> => {
  try {
    if (typeof userPrompt !== "string" || !userPrompt.trim() || userPrompt.length > 4000) {
      return "Please enter a question between 1 and 4,000 characters.";
    }

    const apiKey = process.env.OPENROUTER_API_KEY;
    if (!apiKey) throw new Error("OPENROUTER_API_KEY is not configured");

    const openrouter = new OpenRouter({ apiKey });
    const stream = await openrouter.chat.send({
      chatRequest: {
        model: "openrouter/free",
        messages: [
          { role: "system", content: SYSTEM_INSTRUCTION },
          { role: "user", content: userPrompt.trim() },
        ],
        temperature: 0.7,
        maxTokens: 1000,
        stream: true,
      },
    });

    let response = "";
    for await (const chunk of stream) {
      response += chunk.choices[0]?.delta?.content ?? "";
      if (chunk.usage) {
        console.info("Reasoning tokens:", chunk.usage.completionTokensDetails?.reasoningTokens);
      }
    }

    return response.trim() || "Connection interrupted. Re-establishing link...";
  } catch (error) {
    console.error("Intelligence query failed:", error);
    return "Error: Uplink unstable. Unable to process query.";
  }
};
